#!/usr/bin/env python3
"""fd.py - token-cheap reader/updater for feature design files.

Python 3.8+, standard library only (no pandas). Run from the repo root:

    python .features/tools/fd.py <command> <feature-id> [options]

It exists so agents never have to read a whole design file (and silently get a
truncated copy) or improvise their own parser. DO NOT edit this file during a
feature; report problems to the human.

READ COMMANDS
  hot <id> [--brief]        frontmatter, Resume Here, task table, open OQs, non-complete
                            task blocks, sidecar summary. --brief = table/ids only.
  next <id>                 pick the next executable task and print it (with anchors)
  task <id> T01 [T02 ...]   print specific task blocks
  oq <id> [--open|--unanswered]   print open-question blocks (default: all)
  section <id> [name]       print one section by (partial) heading; no name = list them
  log <id> [-n N]           print the last N progress-log lines (default 10)
  bugs <id> [--pending|--show BUG-ID]   list bugs from the bugs sidecar
  check <id> [T01 ...] [--anchors]      validate structure; --anchors verifies that
                            anchored files/symbols exist in the repo

WRITE COMMANDS
  set <id> T03 <todo|interrupted|complete> [--force]
  set <id> feature <draft|reviewed|in-progress|complete> [--force]
  set <id> resume           recompute Resume Here (progress/next/blocked-by)
  log <id> "text"           append '- YYYY-MM-DD text' to the log sidecar
  bug <id> T03 "summary"    append a bug skeleton to the bugs sidecar, print its id
  backlog add <B-ID> <item> append one item to docs/workflow/BACKLOG.md
                            (append-only; omitted id = next ID, reserved B27-B34 skipped)
  migrate <id>              move an inline Progress Log / Known Issues into sidecars
  start <id> T##            record a start entry for task T## in the progress log
  done <id> T## [--force]   evidence gate: run the task's Verify command, record
                            exit code and output tail; refuses without a matching
                            start; --force logs FORCED instead (D12)

Files (all under <features-dir>/designs_active/, default .features):
  <id>_design.md   hot state (frontmatter, Resume Here, ACs, OQs, Task Plan)
  <id>_log.md      append-only progress log
  <id>_bugs.md     bug entries

Exit code: 0 = ok, 1 = error / structural problem (details on stderr or in output).
"""
import argparse
import datetime
import os
import re
import subprocess
import sys
from pathlib import Path

FEATURE_STATUSES = ("draft", "reviewed", "in-progress", "complete")
TASK_STATUSES = ("todo", "interrupted", "complete")
COMPLEXITIES = ("trivial", "low", "medium", "high")
TASK_FIELDS = ("surface", "skill", "complexity", "depends-on", "traces-to",
               "anchors", "detail", "verify", "status")
FATAL_TASK_FIELDS = ("status", "depends-on")
OQ_KEYS = ("question", "affects", "answer", "decision", "rationale", "status")
PATH_ROLES = ("modify", "delete", "pattern", "read")
ALL_ROLES = PATH_ROLES + ("create", "planned", "search", "greenfield")
POINTER = "> sidecar:"


class FdError(Exception):
    pass


# --------------------------------------------------------------------------- helpers

def norm_key(s):
    for ch in ("\u2010", "\u2011", "\u2012", "\u2013"):
        s = s.replace(ch, "-")
    return s.strip().lower()


def first_word(v):
    v = re.sub(r"[`*]", "", v or "").strip().lower()
    parts = v.split()
    return parts[0].rstrip(",.;:") if parts else ""


def today():
    return datetime.date.today().isoformat()


def structural_mask(lines):
    """True for lines that are real markdown structure (not inside code fences or
    HTML comments). Headings/fields inside comments (e.g. the template's bug
    example) must never be parsed."""
    mask, in_c, in_f = [], False, False
    for ln in lines:
        s = ln.strip()
        if in_c:
            mask.append(False)
            if "-->" in ln:
                in_c = False
            continue
        if s.startswith("```"):
            in_f = not in_f
            mask.append(False)
            continue
        if in_f:
            mask.append(False)
            continue
        if s.startswith("<!--") and s.endswith("-->"):
            mask.append(False)
            continue
        if "<!--" in ln and "-->" not in ln.split("<!--", 1)[1]:
            in_c = True
            mask.append(False)
            continue
        mask.append(True)
    return mask


class Block:
    """A task (### T##) or open question (- **OQ-#**) block."""

    def __init__(self, bid, start, end):
        self.id, self.start, self.end = bid, start, end
        self.f = {}      # key -> [first-line value, line index, [continuation lines]]
        self.boxes = []  # (line index, checked) for '- [ ]' / '- [x]' lines


def body(field):
    if not field:
        return ""
    return "\n".join([field[0]] + [x.strip() for x in field[2]]).strip()


# --------------------------------------------------------------------------- document

class Doc:
    def __init__(self, path):
        path = Path(path)
        if not path.exists():
            raise FdError("design file not found: %s" % path)
        raw = path.read_bytes().decode("utf-8")
        self.path = path
        self.nl = "\r\n" if "\r\n" in raw else "\n"
        self.lines = raw.replace("\r\n", "\n").split("\n")
        self.mask = structural_mask(self.lines)
        self.fm, self.fm_range = {}, None
        self.sections, self.tasks, self.oqs = [], [], []
        self._parse()

    # ---- parsing
    def _trim(self, start, end):
        L = self.lines
        while end > start + 1:
            s = L[end - 1].strip()
            if s == "" or s == "---" or (s.startswith("<!--") and s.endswith("-->")):
                end -= 1
            else:
                break
        return end

    def _parse(self):
        L = self.lines
        if L and L[0].strip() == "---":
            for i in range(1, len(L)):
                if L[i].strip() == "---":
                    self.fm_range = (1, i)
                    break
            if self.fm_range:
                for i in range(*self.fm_range):
                    m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", L[i])
                    if m:
                        k, v = m.group(1), m.group(2)
                        if k != "title":
                            v = re.sub(r"\s+#.*$", "", v)
                        self.fm[k] = [v.strip(), i]

        heads = [i for i, ln in enumerate(L) if self.mask[i] and ln.startswith("## ")]
        for n, i in enumerate(heads):
            end = heads[n + 1] if n + 1 < len(heads) else len(L)
            self.sections.append((L[i][3:].strip(), i, end))

        sec = self.section("task plan")
        if sec:
            _, s, e = sec
            h3 = [i for i in range(s + 1, e) if self.mask[i] and L[i].startswith("### ")]
            for i in h3:
                m = re.match(r"^### (T\d+)\b", L[i])
                if not m:
                    continue
                nxt = min([h for h in h3 if h > i] + [e])
                t = Block(m.group(1), i, self._trim(i, nxt))
                cur = None
                for j in range(i + 1, t.end):
                    if not self.mask[j]:
                        continue
                    fm = re.match(r"^- \*\*([^*]+?):\*\*\s*(.*)$", L[j])
                    if fm:
                        cur = [fm.group(2).strip(), j, []]
                        t.f[norm_key(fm.group(1))] = cur
                    elif cur is not None and L[j].strip() and L[j].strip() != "---":
                        cur[2].append(L[j])
                    bm = re.match(r"^\s*- \[([ xX])\]", L[j])
                    if bm:
                        t.boxes.append((j, bm.group(1) in "xX"))
                self.tasks.append(t)

        sec = self.section("open questions")
        if sec:
            _, s, e = sec
            starts = [i for i in range(s + 1, e)
                      if self.mask[i] and re.match(r"^- \*\*(OQ-[^*\s]+)\*\*", L[i])]
            for n, i in enumerate(starts):
                nxt = starts[n + 1] if n + 1 < len(starts) else e
                q = Block(re.match(r"^- \*\*(OQ-[^*\s]+)\*\*", L[i]).group(1), i, self._trim(i, nxt))
                cur = None
                for j in range(i + 1, q.end):
                    if not self.mask[j]:
                        continue
                    fm = re.match(r"^\s*- \*\*([^*]+?):\*\*\s*(.*)$", L[j])
                    if fm and norm_key(fm.group(1)) in OQ_KEYS:
                        cur = [fm.group(2).strip(), j, []]
                        q.f[norm_key(fm.group(1))] = cur
                    elif cur is not None and L[j].strip() and L[j].strip() != "---":
                        cur[2].append(L[j])
                self.oqs.append(q)

    # ---- accessors
    def fmv(self, k, default=""):
        return self.fm[k][0] if k in self.fm else default

    def set_fm(self, k, v):
        if k not in self.fm:
            raise FdError("frontmatter key '%s' not found" % k)
        i = self.fm[k][1]
        self.lines[i] = re.sub(r"^(%s:\s*)\S+" % re.escape(k), lambda m: m.group(1) + v, self.lines[i], count=1)
        self.fm[k][0] = v

    def section(self, sub):
        sub = sub.lower()
        for name, s, e in self.sections:
            if sub in name.lower():
                return name, s, e
        return None

    def sec_text(self, sec):
        _, s, e = sec
        return "\n".join(self.lines[s:self._trim(s, e)])

    def raw(self, blk):
        return "\n".join(self.lines[blk.start:blk.end])

    def resume(self):
        out, sec = {}, self.section("resume here")
        if sec:
            for i in range(sec[1] + 1, sec[2]):
                m = re.match(r"^\*\*([A-Za-z-]+):\*\*\s*(.*)$", self.lines[i])
                if m:
                    out[m.group(1).lower()] = [m.group(2).strip(), i]
        return out

    def by_id(self, tid):
        for t in self.tasks:
            if t.id.upper() == tid.upper():
                return t
        raise FdError("task %s not found (have: %s)" % (tid, ", ".join(t.id for t in self.tasks) or "none"))

    def task_status(self, t):
        return first_word(t.f.get("status", [""])[0])

    def task_cx(self, t):
        return first_word(t.f.get("complexity", [""])[0])

    def deps(self, t):
        v = body(t.f.get("depends-on"))
        return [] if first_word(v) == "none" else re.findall(r"T\d+", v)

    def set_task_status(self, t, s):
        i = t.f["status"][1]
        self.lines[i] = re.sub(r"^(\s*- \*\*Status:\*\*\s*)\S+", lambda m: m.group(1) + s, self.lines[i], count=1)
        t.f["status"][0] = s

    def oq_open(self, q):
        return first_word(q.f.get("status", [""])[0]) != "resolved"

    def oq_answered(self, q):
        b = body(q.f.get("answer"))
        return bool(b) and not re.match(r"^\(?\s*to be (provided|recorded)", b, re.I)

    def affects(self, q, tid):
        v = body(q.f.get("affects"))
        if re.search(r"\ball\b", v, re.I):
            return True
        return int(tid[1:]) in {int(x) for x in re.findall(r"T(\d+)", v)}

    def save(self):
        self.path.write_bytes(self.nl.join(self.lines).encode("utf-8"))

    # ---- validation
    def validate(self):
        P = []

        def err(msg, fatal=False):
            P.append(("ERROR", fatal, msg))

        def warn(msg):
            P.append(("WARN", False, msg))

        for k in ("feature-id", "title", "status", "last-updated"):
            if k not in self.fm:
                err("frontmatter missing '%s'" % k, True)
        st = first_word(self.fmv("status"))
        if st and st not in FEATURE_STATUSES:
            err("frontmatter status '%s' not in %s" % (st, "|".join(FEATURE_STATUSES)), True)
        rs = self.resume()
        for k in ("progress", "next", "blocked-by"):
            if k not in rs:
                err("Resume Here is missing the '**%s:**' line" % k, True)
        if not self.section("task plan"):
            err("no '## Task Plan' section", True)
        elif not self.tasks:
            err("no '### T##' blocks under '## Task Plan'", True)

        ids, seen = {t.id for t in self.tasks}, set()
        for t in self.tasks:
            if t.id in seen:
                err("duplicate task id %s" % t.id, True)
            seen.add(t.id)
            for k in TASK_FIELDS:
                if k not in t.f:
                    err("%s: missing field '%s'" % (t.id, k), k in FATAL_TASK_FIELDS)
            if "status" in t.f and self.task_status(t) not in TASK_STATUSES:
                err("%s: status '%s' not in %s" % (t.id, self.task_status(t), "|".join(TASK_STATUSES)), True)
            if "complexity" in t.f and self.task_cx(t) not in COMPLEXITIES:
                err("%s: complexity '%s' not in %s" % (t.id, self.task_cx(t), "|".join(COMPLEXITIES)))
            for d in self.deps(t):
                if d not in ids:
                    err("%s: depends-on unknown task %s" % (t.id, d), True)

        remaining = {t.id: set(self.deps(t)) & ids for t in self.tasks}
        done, changed = set(), True
        while changed:
            changed = False
            for tid, d in list(remaining.items()):
                if d <= done:
                    done.add(tid)
                    del remaining[tid]
                    changed = True
        if remaining:
            err("dependency cycle among: %s" % ", ".join(sorted(remaining)), True)

        for q in self.oqs:
            for k in ("question", "affects", "answer", "status"):
                if k not in q.f:
                    err("%s: missing field '%s'" % (q.id, k))
            if "status" in q.f and first_word(q.f["status"][0]) not in ("open", "resolved"):
                err("%s: status must be open|resolved" % q.id)
            if first_word(q.f.get("status", [""])[0]) == "resolved" and not self.oq_answered(q):
                warn("%s is resolved but has no Answer" % q.id)

        for t in self.tasks:
            anchors = parse_anchors(t)
            paths = set()
            for role, toks, raw in anchors:
                if role not in ALL_ROLES:
                    warn("%s: unrecognised anchor role in: %s" % (t.id, raw))
                elif role in PATH_ROLES + ("create",) and not toks:
                    warn("%s: anchor without a path: %s" % (t.id, raw))
                elif role in ("modify", "create", "delete") and toks:
                    paths.add(toks[0])
                elif role == "planned":
                    ref = re.search(r"T\d+", raw)
                    if not ref or ref.group(0) not in ids:
                        warn("%s: 'planned' anchor must reference an existing task (<- T##): %s" % (t.id, raw))
            if self.task_cx(t) in ("trivial", "low") and len(paths) > 3:
                warn("%s: %d files modified/created/deleted but complexity is %s (limit ~3)"
                     % (t.id, len(paths), self.task_cx(t)))
            if "anchors" in t.f and not anchors:
                err("%s: Anchors is empty (use 'greenfield' if there is no existing code)" % t.id)

        if len(self.tasks) >= 1:
            tail = "\n".join(self.raw(t) for t in self.tasks[-2:])
            if not re.search(r"code[- ]review", tail, re.I):
                warn("no code-review task in the last two positions of the Task Plan")

        if "progress" in rs:
            m = re.match(r"(\d+)/(\d+)", rs["progress"][0])
            if m:
                total = len(self.tasks)
                comp = sum(1 for t in self.tasks if self.task_status(t) == "complete")
                if (int(m.group(1)), int(m.group(2))) != (comp, total):
                    warn("Resume Here progress says %s but tasks say %d/%d (run: fd.py set <id> resume)"
                         % (rs["progress"][0], comp, total))

        for name in ("progress log", "known issues"):
            sec = self.section(name)
            if sec:
                n = sum(1 for i in range(sec[1] + 1, sec[2])
                        if self.mask[i] and self.lines[i].strip() not in ("", "---")
                        and not self.lines[i].startswith(POINTER))
                if n:
                    warn("inline '%s' has %d lines; run: fd.py migrate <id>" % (sec[0], n))
        return P


# --------------------------------------------------------------------------- anchors

def parse_anchors(t):
    f = t.f.get("anchors")
    out = []
    if not f:
        return out
    for ln in ([f[0]] if f[0] else []) + f[2]:
        s = ln.strip()
        if s.startswith("- "):
            s = s[2:].strip()
        if not s or s.startswith("<!--"):
            continue
        m = re.match(r"(?i)^(search|greenfield)\b", s)
        if m:
            out.append((m.group(1).lower(), [], s))
            continue
        toks = re.findall(r"`([^`]*)`", s)
        if not toks:
            out.append(("?", [], s))
            continue
        out.append((toks[0].strip().rstrip(":").lower(), [x.strip() for x in toks[1:]], s))
    return out


def symbol_needles(sym):
    sym = sym.strip()
    m = re.match(r"""(?i)^grep:\s*["']?(.*?)["']?$""", sym)
    if m:
        return [m.group(1)]
    base = re.sub(r"\(.*?\)\s*$", "", sym).strip()
    cands = [base]
    ids = re.findall(r"[A-Za-z_$][\w$]*", base)
    if ids and ids[-1] != base:
        cands.append(ids[-1])
    return cands


def verify_anchors(doc, tasks, root):
    """Return (problem_lines, ok_count, bad_count, unresolved_count)."""
    out, ok, bad, unres = [], 0, 0, 0
    cache = {}
    st = {t.id: doc.task_status(t) for t in doc.tasks}
    for t in tasks:
        for role, toks, raw in parse_anchors(t):
            tag = "%s %s" % (t.id, role)
            if role in PATH_ROLES:
                if not toks:
                    out.append("BAD-FORMAT   %s: %s" % (tag, raw))
                    bad += 1
                    continue
                p = root / toks[0]
                if not p.is_file():
                    out.append("MISSING-FILE %s: %s" % (tag, toks[0]))
                    bad += 1
                    continue
                if len(toks) > 1 and toks[1]:
                    if p not in cache:
                        cache[p] = p.read_bytes().decode("utf-8", "ignore")
                    if any(n and n in cache[p] for n in symbol_needles(toks[1])):
                        ok += 1
                    else:
                        out.append("MISSING-SYMBOL %s: '%s' not found in %s" % (tag, toks[1], toks[0]))
                        bad += 1
                else:
                    ok += 1
            elif role == "create":
                if toks and (root / toks[0]).exists():
                    out.append("NOTE         %s: %s already exists (modify instead?)" % (tag, toks[0]))
                ok += 1
            elif role == "planned":
                ref = re.search(r"T\d+", raw)
                if ref and st.get(ref.group(0)) == "complete":
                    out.append("RE-ANCHOR    %s: %s is complete; replace with the real location" % (tag, ref.group(0)))
                    unres += 1
                else:
                    ok += 1
            elif role == "search":
                out.append("UNRESOLVED   %s: %s" % (tag, raw))
                unres += 1
            elif role == "greenfield":
                ok += 1
            else:
                out.append("BAD-FORMAT   %s: %s" % (tag, raw))
                bad += 1
    return out, ok, bad, unres


# --------------------------------------------------------------------------- next / resume

def pick_next(doc):
    """-> (task | None, blocking_oq_ids, reason)"""
    st = {t.id: doc.task_status(t) for t in doc.tasks}
    pend = sorted((t for t in doc.tasks if st[t.id] != "complete"), key=lambda t: int(t.id[1:]))
    if not pend:
        return None, [], "all tasks complete"
    chosen = next((t for t in pend if st[t.id] == "interrupted"), None)
    if chosen is None:
        chosen = next((t for t in pend if all(st.get(d) == "complete" for d in doc.deps(t))), None)
    if chosen is None:
        waits = "; ".join("%s waits on %s" % (t.id, ",".join(
            "%s[%s]" % (d, st.get(d, "?")) for d in doc.deps(t) if st.get(d) != "complete")) for t in pend)
        return None, [], "no executable task: " + waits
    blk = [q.id for q in doc.oqs if doc.oq_open(q) and doc.affects(q, chosen.id)]
    return chosen, blk, ""


def recompute_resume(doc):
    rs = doc.resume()
    for k in ("progress", "next", "blocked-by"):
        if k not in rs:
            raise FdError("Resume Here is missing the '**%s:**' line" % k)
    total = len(doc.tasks)
    done = sum(1 for t in doc.tasks if doc.task_status(t) == "complete")
    nxt, blk, _ = pick_next(doc)
    open_all = [q.id for q in doc.oqs if doc.oq_open(q)]
    if first_word(doc.fmv("status")) == "draft" and open_all:
        nv, bv = "review", open_all
    elif nxt is None:
        nv, bv = ("none", []) if done == total else ("review", open_all)
    elif blk:
        nv, bv = "review", blk
    else:
        nv, bv = nxt.id, []
    vals = {"progress": "%d/%d tasks complete" % (done, total), "next": nv,
            "blocked-by": ", ".join(bv) or "none"}
    for k, v in vals.items():
        i = rs[k][1]
        doc.lines[i] = "**%s:** %s" % (k, v)
    return vals


# --------------------------------------------------------------------------- sidecars

def paths_for(features, fid):
    d = Path(features) / "designs_active"
    return d / ("%s_design.md" % fid), d / ("%s_log.md" % fid), d / ("%s_bugs.md" % fid)


def append_line(path, header, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    new = (not path.exists()) or path.stat().st_size == 0
    glue = ""
    if not new:
        with open(path, "rb") as fh:
            fh.seek(-1, os.SEEK_END)
            if fh.read(1) != b"\n":
                glue = "\n"
    with open(path, "a", encoding="utf-8", newline="\n") as fh:
        if new:
            fh.write(header + "\n\n")
        fh.write(glue + text.rstrip("\n") + "\n")


def read_log_lines(path):
    if not path.exists():
        return []
    return [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln.startswith("- ")]


def log_events(logp, tid):
    """Return [(event, line)] for start/done/forced log entries about task tid,
    in file order. An entry looks like '- 2026-11-06 T01 done: exit=0 cmd=...'."""
    out = []
    for ln in read_log_lines(logp):
        parts = ln.split(None, 2)
        if len(parts) < 3:
            continue
        m = re.match(r"^(T\d+)\s+(start|done|forced)\b", parts[2], re.I)
        if m and m.group(1).upper() == tid.upper():
            out.append((m.group(2).lower(), ln))
    return out


def run_verify(cmd, root):
    """Run a task Verify command and return (exit code, combined output)."""
    p = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=str(root))
    out = (p.stdout or "") + (p.stderr or "")
    return p.returncode, out


def parse_bugs(path):
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    parts = re.split(r"(?m)^(?=### Bug )", text)
    out = []
    for p in parts:
        m = re.match(r"### Bug (\S+)\s*[—–-]+\s*(.*)", p)
        if not m:
            continue
        task = re.search(r"\*\*Task:\*\*\s*(.*)", p)
        outc = re.search(r"\*\*Outcome:\*\*\s*(.*)", p)
        out.append({"id": m.group(1), "summary": m.group(2).strip(), "text": p.rstrip(),
                    "task": task.group(1).strip() if task else "?",
                    "outcome": outc.group(1).strip() if outc else "pending"})
    return out


def is_pending(b):
    return first_word(b["outcome"]) in ("", "pending")


BACKLOG_ID_RE = re.compile(r"^B(\d+)$")
# B27-B34 are reserved by PLAN section 5 (D6); IDs continue from B35.
BACKLOG_RESERVED = set(range(27, 35))


def backlog_ids(path):
    ids = set()
    for ln in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*(B\d+)\s*\|", ln)
        if m:
            ids.add("B%s" % m.group(1))
    return ids


def next_backlog_id(path):
    best = 0
    for ln in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*(B(\d+))\s*\|", ln)
        if m:
            best = max(best, int(m.group(2)))
    nid = best + 1
    while nid in BACKLOG_RESERVED:
        nid += 1
    return "B%d" % nid



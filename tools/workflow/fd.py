class Ctx:
    def __init__(self, a):
        self.a = a
        self.features = Path(getattr(a, "dir", None) or os.environ.get("FD_FEATURES_DIR", ".features"))
        self.design, self.logp, self.bugp = paths_for(
            self.features, getattr(a, "id", None) or "B0")
        self.root = Path(a.root) if a.root else self.features.resolve().parent

    def doc(self):
        return Doc(self.design)


def print_problems(probs, levels=("ERROR", "WARN"), prefix=""):
    for lvl, fatal, msg in probs:
        if lvl in levels:
            print("%s%s%s: %s" % (prefix, lvl, " (fatal)" if fatal else "", msg))


def cmd_hot(c):
    d = c.doc()
    probs = d.validate()
    fatal = [p for p in probs if p[1]]
    print("== %s (%s, %d lines) ==" % (c.a.id, c.design, len(d.lines)))
    if fatal:
        print("!! STRUCTURAL PROBLEMS - output below may be wrong; tell the human:")
        print_problems(fatal, prefix="!! ")
    for k in ("feature-id", "title", "status", "created", "last-updated", "surfaces", "skills-engaged"):
        if k in d.fm:
            print("%s: %s" % (k, d.fm[k][0]))
    print("\n-- Resume Here")
    for k, (v, _) in d.resume().items():
        print("%s: %s" % (k, v))
    print("\n-- Tasks")
    for t in d.tasks:
        print("%s [%s] %s deps=%s" % (t.id, d.task_status(t) or "?", d.task_cx(t) or "?",
                                      ",".join(d.deps(t)) or "none"))
    opn = [q for q in d.oqs if d.oq_open(q)]
    print("\n-- Open questions: %d open, %d resolved" % (len(opn), len(d.oqs) - len(opn)))
    if c.a.brief:
        for q in opn:
            print("%s affects=%s answered=%s" % (q.id, body(q.f.get("affects")) or "?", "yes" if d.oq_answered(q) else "no"))
    else:
        for q in opn:
            print(d.raw(q))
        act = [t for t in d.tasks if d.task_status(t) != "complete"]
        print("\n-- Task blocks (not complete)")
        for t in act:
            print(d.raw(t) + "\n")
    logs, bugs = read_log_lines(c.logp), parse_bugs(c.bugp)
    print("-- Sidecars")
    print("log: %d entries%s" % (len(logs), "; last 3:" if logs else ""))
    for ln in logs[-3:]:
        print("  " + ln)
    print("bugs: %d (%d pending)%s" % (len(bugs), sum(is_pending(b) for b in bugs),
                                       "  -> fd.py bugs %s --pending" % c.a.id if bugs else ""))
    print("\n-- Sections: " + ", ".join("%s (%d lines)" % (n, e - s) for n, s, e in d.sections))
    print("   read one with: fd.py section %s \"<name>\"" % c.a.id)
    for lvl, f, m in probs:
        if lvl == "WARN":
            print("warn: " + m)
    return 1 if fatal else 0


def cmd_next(c):
    d = c.doc()
    fatal = [p for p in d.validate() if p[1]]
    if fatal:
        print_problems(fatal)
        raise FdError("structural problems; fix the design file before continuing")
    t, blk, reason = pick_next(d)
    if t is None:
        print("next: none")
        print("reason: " + reason)
        return 0
    print("next: %s" % t.id)
    print("status: %s" % d.task_status(t))
    print("blocked-by: %s" % (", ".join(blk) or "none"))
    if blk:
        print("ACTION: stop. Set blocked-by in Resume Here and send the human to /feature-review.")
    print("---")
    print(d.raw(t))
    return 0


def cmd_task(c):
    d = c.doc()
    for tid in c.a.tasks:
        print(d.raw(d.by_id(tid)) + "\n")
    return 0


def cmd_oq(c):
    d = c.doc()
    sel = d.oqs
    if c.a.open:
        sel = [q for q in sel if d.oq_open(q)]
    if c.a.unanswered:
        sel = [q for q in sel if not d.oq_answered(q)]
    for q in sel:
        print(d.raw(q))
    if c.a.unanswered:
        print("\nUNANSWERED: " + (", ".join(q.id for q in sel) or "none (all answered)"))
    else:
        print("\n%d shown of %d total; %d open, %d unanswered" % (
            len(sel), len(d.oqs), sum(d.oq_open(q) for q in d.oqs), sum(not d.oq_answered(q) for q in d.oqs)))
    return 0


def cmd_section(c):
    d = c.doc()
    if not c.a.name:
        for n, s, e in d.sections:
            print("%s  (%d lines)" % (n, e - s))
        return 0
    sec = d.section(c.a.name)
    if not sec:
        raise FdError("no section matching '%s'. Sections: %s" % (c.a.name, ", ".join(n for n, _, _ in d.sections)))
    print(d.sec_text(sec))
    return 0


def cmd_log(c):
    if c.a.text:
        text = " ".join(c.a.text).strip()
        append_line(c.logp, "# Progress Log - %s (append-only)" % c.a.id, "- %s %s" % (today(), text))
        print("logged -> %s" % c.logp)
        return 0
    lines = read_log_lines(c.logp)
    print("(%d entries; showing last %d)" % (len(lines), min(c.a.n, len(lines))))
    for ln in lines[-c.a.n:]:
        print(ln)
    return 0


def cmd_start(c):
    """Record a start entry for task T## in the progress-log sidecar."""
    d = c.doc()
    t = d.by_id(c.a.task)
    verify = body(t.f.get("verify", [""]))
    append_line(c.logp, "# Progress Log - %s (append-only)" % c.a.id,
                "- %s %s start: verify=%r" % (today(), t.id, verify))
    print("started %s -> %s" % (t.id, c.logp))
    print("verify: %s" % verify)
    return 0


def cmd_done(c):
    """Evidence gate: run the task's Verify command, record exit code and tail.

    Refuses without a matching start entry unless --force (logs FORCED per D12)."""
    d = c.doc()
    t = d.by_id(c.a.task)
    ev = log_events(c.logp, t.id)
    if not any(e == "start" for e, _ in ev) and not c.a.force:
        raise FdError("%s: no start entry; run 'fd.py start %s %s' first (or --force)"
                      % (t.id, c.a.id, t.id))
    verify = body(t.f.get("verify", [""]))
    exit_code, out = run_verify(verify, c.root)
    tail = "\n".join(out.splitlines()[-20:]) if out else ""
    tag = "forced" if c.a.force else "done"
    append_line(c.logp, "# Progress Log - %s (append-only)" % c.a.id,
                "- %s %s %s: exit=%d cmd=%r tail=%r" % (today(), t.id, tag,
                                                        exit_code, verify, tail))
    print("gate %s: %s -> exit=%d" % (tag.upper(), t.id, exit_code))
    print("cmd: %s" % verify)
    if tail:
        print("tail:")
        print(tail)
    else:
        print("tail: (no output)")
    return exit_code


def cmd_bug(c):
    d = c.doc()
    t = d.by_id(c.a.task)
    n = int(t.id[1:])
    prefix = "%s-%d-" % (c.a.id, n)
    existing = [int(m.group(1)) for b in parse_bugs(c.bugp)
                for m in [re.match(re.escape(prefix) + r"(\d+)$", b["id"])] if m]
    bid = "%s%d" % (prefix, max(existing or [0]) + 1)
    summary = c.a.summary.strip()
    skeleton = "\n".join([
        "", "### Bug %s \u2014 %s" % (bid, summary),
        "- **Detected:** %s - <how it was observed>" % today(),
        "- **Task:** %s" % t.id,
        "- **Location:** `path` \u2192 `symbol`",
        "- **Root cause:** pending",
        "- **Resolution:** pending",
        "- **Rationale:** pending",
        "- **Recurrence prevention:** pending",
        "- **Outcome:** pending", ""])
    append_line(c.bugp, "# Known Issues / Bugs - %s" % c.a.id, skeleton)
    append_line(c.logp, "# Progress Log - %s (append-only)" % c.a.id,
                "- %s bug %s recorded: %s" % (today(), bid, summary))
    print("bug id: %s\nfile: %s\nFill in the pending fields by editing that entry; never guess a root cause." % (bid, c.bugp))
    return 0


def cmd_backlog_add(c):
    """Append one item to docs/workflow/BACKLOG.md (append-only).

    Existing rows are never edited. Give an explicit id (e.g. B27); omit it
    to get the next ID (reserved B27-B34 are skipped).
    """
    backlog = c.root / "docs" / "workflow" / "BACKLOG.md"
    if not backlog.exists():
        raise FdError("backlog not found: %s" % backlog)
    bid = c.a.id
    tokens = list(c.a.item or [])
    if bid and BACKLOG_ID_RE.match(bid):
        bid = "B%s" % BACKLOG_ID_RE.match(bid).group(1)
    else:
        if bid:
            tokens.insert(0, bid)
        bid = next_backlog_id(backlog)
    if not tokens:
        raise FdError("backlog add: item text is required")
    item = " ".join(t.strip() for t in tokens)
    if "|" in item:
        raise FdError("backlog add: item text may not contain '|'")
    existing = backlog_ids(backlog)
    if bid in existing:
        raise FdError("backlog add: %s already exists (append-only; existing rows are never edited)" % bid)
    row = "| %s | %s | %s | %s | %s | %s | %s |" % (
        bid, item, c.a.source, c.a.suggested_phase, c.a.size, c.a.status, c.a.phase)
    raw = backlog.read_text(encoding="utf-8", newline="")
    nl = "\r\n" if "\r\n" in raw else "\n"
    if not raw.endswith(nl):
        raw += nl
    with open(backlog, "w", encoding="utf-8", newline="") as fh:
        fh.write(raw + row + nl)
    print("appended %s -> %s" % (bid, backlog))
    print(row)
    return 0


def cmd_bugs(c):
    bugs = parse_bugs(c.bugp)
    if c.a.show:
        m = [b for b in bugs if c.a.show in b["id"]]
        if not m:
            raise FdError("no bug matching '%s'" % c.a.show)
        for b in m:
            print(b["text"])
        return 0
    sel = [b for b in bugs if is_pending(b)] if c.a.pending else bugs
    for b in sel:
        print("%s | %s | %s | %s" % (b["id"], b["task"], first_word(b["outcome"]) or "pending", b["summary"]))
    print("(%d shown of %d)" % (len(sel), len(bugs)))
    return 0


def cmd_check(c):
    d = c.doc()
    probs = d.validate()
    print_problems(probs)
    errs = sum(1 for p in probs if p[0] == "ERROR")
    warns = sum(1 for p in probs if p[0] == "WARN")
    bad = 0
    if c.a.anchors:
        sel = [d.by_id(x) for x in c.a.tasks] if c.a.tasks else d.tasks
        lines, ok, bad, unres = verify_anchors(d, sel, c.root)
        for ln in lines:
            print(ln)
        print("anchors: %d ok, %d bad, %d unresolved (repo root: %s)" % (ok, bad, unres, c.root))
    print("check: %d errors, %d warnings" % (errs, warns))
    return 1 if (errs or bad) else 0


def cmd_set(c):
    d = c.doc()
    fatal = [p for p in d.validate() if p[1]]
    if fatal:
        print_problems(fatal)
        raise FdError("structural problems; fix the design file before continuing")
    a, msgs = c.a, []
    fstat = first_word(d.fmv("status"))
    if a.target == "resume":
        pass
    elif a.target == "feature":
        v = (a.value or "").lower()
        if v not in FEATURE_STATUSES:
            raise FdError("feature status must be one of %s" % "|".join(FEATURE_STATUSES))
        if v == "complete" and not a.force:
            left = [t.id for t in d.tasks if d.task_status(t) != "complete"]
            if left:
                raise FdError("tasks not complete: %s (use --force to override)" % ", ".join(left))
            sec = d.section("acceptance")
            unticked = [i for i in range(sec[1], sec[2]) if d.mask[i] and re.match(r"^\s*- \[ \]", d.lines[i])] if sec else []
            if unticked:
                raise FdError("%d acceptance criteria are not ticked (tick them in the file, or --force)" % len(unticked))
        d.set_fm("status", v)
        msgs.append("feature status -> %s" % v)
    elif re.fullmatch(r"[Tt]\d+", a.target):
        v = (a.value or "").lower()
        if v not in TASK_STATUSES:
            raise FdError("task status must be one of %s" % "|".join(TASK_STATUSES))
        t = d.by_id(a.target)
        if fstat == "draft" and not a.force:
            raise FdError("feature is still 'draft'; run /feature-review first (or --force)")
        if v == "complete":
            unchecked = [d.lines[i].strip() for i, ok in t.boxes if not ok]
            if unchecked and not a.force:
                raise FdError("%s has unchecked subtasks (tick them in the file first):\n  %s" % (t.id, "\n  ".join(unchecked)))
        d.set_task_status(t, v)
        msgs.append("%s -> %s" % (t.id, v))
        if v in ("interrupted", "complete") and fstat == "reviewed":
            d.set_fm("status", "in-progress")
            msgs.append("feature status reviewed -> in-progress")
    else:
        raise FdError("target must be a task id (T03), 'feature', or 'resume'")
    if "last-updated" in d.fm:
        d.set_fm("last-updated", today())
    vals = recompute_resume(d)
    d.save()
    print("; ".join(msgs + ["resume: %s | next=%s | blocked-by=%s" % (vals["progress"], vals["next"], vals["blocked-by"])]))
    if all(d.task_status(t) == "complete" for t in d.tasks) and d.tasks and first_word(d.fmv("status")) != "complete":
        print("All tasks complete. Tick acceptance criteria, then: fd.py set %s feature complete" % c.a.id)
    return 0


def cmd_migrate(c):
    moved = []
    for name, target, header in (
            ("progress log", c.logp, "# Progress Log - %s (append-only)" % c.a.id),
            ("known issues", c.bugp, "# Known Issues / Bugs - %s" % c.a.id)):
        d = c.doc()
        sec = d.section(name)
        if not sec:
            continue
        _, s, e = sec
        content = [d.lines[i] for i in range(s + 1, e)
                   if d.mask[i] and d.lines[i].strip() not in ("", "---") and not d.lines[i].startswith(POINTER)]
        if content:
            new = (not target.exists()) or target.stat().st_size == 0
            target.parent.mkdir(parents=True, exist_ok=True)
            with open(target, "a", encoding="utf-8", newline="\n") as fh:
                if new:
                    fh.write(header + "\n\n")
                fh.write("\n".join(content).rstrip("\n") + "\n")
            moved.append("%s: %d lines -> %s" % (sec[0], len(content), target.name))
        cmd = "fd.py log %s" % c.a.id if target == c.logp else "fd.py bug %s T## \"summary\"" % c.a.id
        pointer = "%s `%s` (append-only). Use `%s`." % (POINTER, target.name, cmd)
        d.lines[s + 1:e] = ["", pointer, "", "---", ""]
        d.save()
    print("; ".join(moved) if moved else "nothing to migrate")
    return 0



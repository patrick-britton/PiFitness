def build_parser():
    ap = argparse.ArgumentParser(prog="fd.py", description="Feature design-file helper (stdlib only).",
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument("--dir", default=os.environ.get("FD_FEATURES_DIR", ".features"), help="features dir (default .features)")
    ap.add_argument("--root", default=None, help="repo root for anchor checks (default: parent of --dir)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def add(name, fn, h):
        p = sub.add_parser(name, help=h)
        p.add_argument("id", help="feature id")
        p.set_defaults(fn=fn)
        return p

    p = add("hot", cmd_hot, "hot state of the design file")
    p.add_argument("--brief", action="store_true")
    add("next", cmd_next, "next executable task")
    p = add("task", cmd_task, "print task blocks")
    p.add_argument("tasks", nargs="+")
    p = add("oq", cmd_oq, "open questions")
    p.add_argument("--open", action="store_true")
    p.add_argument("--unanswered", action="store_true")
    p = add("section", cmd_section, "print a section")
    p.add_argument("name", nargs="?")
    p = add("log", cmd_log, "read or append the progress log")
    p.add_argument("text", nargs="*")
    p.add_argument("-n", type=int, default=10)
    p = add("bug", cmd_bug, "record a bug skeleton")
    p.add_argument("task")
    p.add_argument("summary")
    p = add("bugs", cmd_bugs, "list bugs")
    p.add_argument("--pending", action="store_true")
    p.add_argument("--show", default=None)
    p = add("start", cmd_start, "record a start entry for a task")
    p.add_argument("task", help="task id (T##)")
    p = add("done", cmd_done, "evidence gate: run a task's Verify command")
    p.add_argument("task", help="task id (T##)")
    p.add_argument("--force", action="store_true")
    p = add("check", cmd_check, "validate the design file")
    p.add_argument("tasks", nargs="*")
    p.add_argument("--anchors", action="store_true")
    p = add("set", cmd_set, "update status / resume")
    p.add_argument("target", help="T## | feature | resume")
    p.add_argument("value", nargs="?")
    p.add_argument("--force", action="store_true")
    add("migrate", cmd_migrate, "move inline log/bugs into sidecars")
    p = sub.add_parser("backlog", help="backlog file operations")
    bsub = p.add_subparsers(dest="backlog_cmd", required=True)
    pa = bsub.add_parser("add", help="append one item to the backlog")
    pa.add_argument("id", nargs="?", default=None, help="backlog id (e.g. B27); omitted = next ID")
    pa.add_argument("item", nargs="*", help="item text")
    pa.add_argument("--source", default="fd.py backlog add")
    pa.add_argument("--suggested-phase", default="Phase 5")
    pa.add_argument("--size", default="Small")
    pa.add_argument("--status", default="open")
    pa.add_argument("--phase", default="5")
    pa.set_defaults(fn=cmd_backlog_add)
    return ap


def main(argv=None):
    a = build_parser().parse_args(argv)
    try:
        return a.fn(Ctx(a)) or 0
    except FdError as e:
        sys.stderr.write("fd.py: error: %s\n" % e)
        return 1
    except BrokenPipeError:  # e.g. `fd.py hot x | head`
        try:
            sys.stdout.close()
        except Exception:
            pass
        return 0


if __name__ == "__main__":
    sys.exit(main())
